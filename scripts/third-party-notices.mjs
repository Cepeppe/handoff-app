#!/usr/bin/env node
/**
 * Writes the crate list of the third-party notices from the graph Cargo resolves for the
 * shipped Windows build (T-052).
 *
 * `docs/third-party-notices.md` and `docs/it/third-party-notices.md` carry, between two
 * marker comments, one row per Rust crate the application is built from. The rows are not
 * written by hand: this script reads `cargo metadata` for `x86_64-pc-windows-msvc` with the
 * lock file as it is, which resolves the **default features** only — so a crate behind a
 * feature the shipped build does not enable (`reqwest` behind `net`, `DEVIATIONS.md` T-051)
 * is not listed, because it is not in the binary — and follows the normal dependency edges
 * from `handoff-app`. Build scripts' and tests' dependencies are compiled on the build
 * machine and never shipped, so their edges are not followed.
 *
 * Every crate must declare an SPDX `license`; one that does not stops the script, because a
 * row with no licence is a notice that says nothing.
 *
 * Usage (from the repository root, with a toolchain that can run `cargo metadata`):
 *   node scripts/third-party-notices.mjs           rewrite the two lists
 *   node scripts/third-party-notices.mjs --check   exit 1 if either list is stale (CI)
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CRATE_DIR = join(ROOT, 'src-tauri');
const TARGET = 'x86_64-pc-windows-msvc';

export const BEGIN =
  '<!-- crates:begin — generated by scripts/third-party-notices.mjs, do not edit by hand -->';
export const END = '<!-- crates:end -->';

/** The two pages, each with the header row of its own language. */
const PAGES = [
  { path: join(ROOT, 'docs', 'third-party-notices.md'), header: ['Crate', 'Version', 'Licence'] },
  {
    path: join(ROOT, 'docs', 'it', 'third-party-notices.md'),
    header: ['Crate', 'Versione', 'Licenza'],
  },
];

/** `cargo metadata` of the crate, resolved for the shipped target and the locked graph. */
function metadata() {
  const out = execFileSync(
    'cargo',
    ['metadata', '--format-version', '1', '--locked', '--filter-platform', TARGET],
    { cwd: CRATE_DIR, encoding: 'utf8', maxBuffer: 512 * 1024 * 1024 },
  );
  return JSON.parse(out);
}

/**
 * Every package reachable from the root through normal dependency edges, the root excluded,
 * as `{ name, version, license }`, sorted by name and then version.
 */
export function shippedCrates(meta) {
  const nodes = new Map(meta.resolve.nodes.map((node) => [node.id, node]));
  const packages = new Map(meta.packages.map((pkg) => [pkg.id, pkg]));
  const root = meta.resolve.root;
  const reached = new Set([root]);
  const queue = [root];
  while (queue.length > 0) {
    const node = nodes.get(queue.shift());
    for (const dep of node?.deps ?? []) {
      const normal = dep.dep_kinds.some((kind) => kind.kind === null);
      if (normal && !reached.has(dep.pkg)) {
        reached.add(dep.pkg);
        queue.push(dep.pkg);
      }
    }
  }
  reached.delete(root);

  const crates = [...reached].map((id) => {
    const pkg = packages.get(id);
    return { name: pkg.name, version: pkg.version, license: pkg.license ?? null };
  });
  const unlicensed = crates.filter((crate) => !crate.license);
  if (unlicensed.length > 0) {
    throw new Error(
      `no SPDX licence declared by: ${unlicensed.map((c) => `${c.name} ${c.version}`).join(', ')}`,
    );
  }
  return crates.sort((a, b) =>
    a.name === b.name ? (a.version < b.version ? -1 : 1) : a.name < b.name ? -1 : 1,
  );
}

/** The generated block of one page: the markers, a header row and one row per crate. */
export function block(crates, header) {
  const cell = (text) => String(text).replaceAll('|', '\\|');
  const rows = crates.map((c) => `| ${cell(c.name)} | ${cell(c.version)} | ${cell(c.license)} |`);
  return [BEGIN, '', `| ${header.join(' | ')} |`, '|---|---|---|', ...rows, '', END].join('\n');
}

/** `source` with the text between the markers replaced by `generated`. */
export function splice(source, generated, where) {
  const start = source.indexOf(BEGIN);
  const end = source.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`${where} has no "${BEGIN}" … "${END}" block`);
  }
  return source.slice(0, start) + generated + source.slice(end + END.length);
}

const invokedDirectly =
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));

if (invokedDirectly) {
  const check = process.argv.includes('--check');
  const crates = shippedCrates(metadata());
  let stale = 0;
  for (const page of PAGES) {
    const where = relative(ROOT, page.path).replaceAll('\\', '/');
    const before = readFileSync(page.path, 'utf8');
    const after = splice(before, block(crates, page.header), where);
    if (after === before) continue;
    if (check) {
      console.error(`${where}: the crate list is stale; run node scripts/third-party-notices.mjs`);
      stale += 1;
    } else {
      writeFileSync(page.path, after, 'utf8');
      console.error(`${where}: rewritten`);
    }
  }
  if (stale > 0) process.exit(1);
  console.log(`third-party-notices: ${crates.length} crates, ${check ? 'lists are current' : 'done'}`);
}
